#!/usr/bin/env python3
"""Export every palette as one degoog theme, laid out as a degoog store repo.

    python3 tools/degoog_export.py [--out DIR] [--check]

Reads <slug>/desktop/<slug>.app-theme.json (run `rain build` first) and writes:

    package.json             store manifest (degoog Settings -> Store -> Add)
    logo.png                 repo image
    README.md
    themes/rain/theme.json   one theme, palette picked from a select (Configure on the theme card)
    themes/rain/style.css    every palette, keyed on html[data-rain-palette]; light flavour where the spec has one
    themes/rain/author.json

DIR defaults to ../degoog-rain (a checkout of the store repo next to this one).
themes/rain/screenshots/ is left alone (tools/dev/degoog_preview.py makes it).
--check writes nothing and exits 1 if DIR differs from what the export would write.
See tools/README.md ("degoog").
"""
import argparse
import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_theme import contrast, mix, rgb  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
THEME = "themes/rain"
ATTR = "rain-palette"
REPO_URL = "https://github.com/alpine-vortex/rain-themes"
STORE_URL = "https://github.com/alpine-vortex/degoog-rain.git"
ICON = ROOT / "assets/icon/rain-themes-256.png"


def palettes():
    """(spec, app-theme) for every palette with desktop exports, sorted by name."""
    out = []
    for f in sorted(ROOT.glob("*/theme.spec.json")):
        spec = json.loads(f.read_text())
        at = f.parent / "desktop" / f"{spec['slug']}.app-theme.json"
        if at.exists():
            out.append((spec, json.loads(at.read_text())))
    return sorted(out, key=lambda p: p[0]["name"].lower())


def rgba(h, a):
    return "rgba(%d, %d, %d, %s)" % (*(round(x * 255) for x in rgb(h)), a)


def variables(t):
    """degoog's colour variables (src/styles/style.scss, plus the few its components read
    without a default) from one app-theme v1 block (dark top level or its `light`)."""
    bg, text, accent, link = t["background"], t["text"], t["accent"], t["link"]
    visited = accent if accent != link else t["state"]
    return {
        "--bg": bg, "--bg-light": t["raised"], "--bg-hover": t["selected"], "--bg-secondary": t["panel"],
        "--modal-footer": t["panel"],
        "--border": t["border"], "--border-light": t["line"], "--border-color": t["line"],
        "--text-primary": text, "--text-secondary": t["text_secondary"], "--text-muted": t["text_muted"],
        "--text-link": link, "--text-link-visited": visited,
        "--text-cite": t["text_secondary"], "--text-snippet": t["text_secondary"],
        "--search-bar-bg": t["raised"], "--search-bar-bg-hover": t["raised"],
        "--btn-bg": t["raised"], "--btn-text": text,
        "--primary": accent, "--primary-hover": mix(accent, text, 0.25),
        "--primary-rgb": ", ".join(str(round(x * 255)) for x in rgb(accent)),
        "--accent": accent, "--white": t["on_accent"],
        "--danger": t["danger"], "--color-danger": t["danger"], "--warning": t["warning"], "--success": t["positive"],
        # the logo's letters and a few highlights
        "--brand-blue": link, "--brand-yellow": t["warning"],
        "--overlay-bg": rgba(bg, 0.75),
        "--tooltip-bg": text, "--tooltip-text": bg,
    }


def block(selector, t, scheme, indent=""):
    body = "\n".join(f"{indent}  {k}: {v};" for k, v in variables(t).items())
    return f"{indent}{selector} {{\n{indent}  color-scheme: {scheme};\n{body}\n{indent}}}\n"


def stylesheet(pals):
    """The theme's CSS loads after degoog's, so [data-rain-palette] (0,1,0) beats its :root and
    [data-theme] blocks; the light flavour adds [data-theme="light"] or, with no explicit choice,
    the OS preference. Palettes without a light flavour stay dark under the light toggle."""
    parts = [f"/* Rain for degoog: generated by rain-themes tools/degoog_export.py. Do not edit.\n"
             f"   {REPO_URL} */\n"]
    for spec, t in pals:
        sel = f'[data-{ATTR}="{spec["slug"]}"]'
        L = t.get("light")
        parts.append(f"/* {spec['name']}" + (f" / {L['flavour']}" if L else "") + " */\n")
        parts.append(block(sel, t, "dark"))
        if L:
            parts.append(block(f'{sel}[data-theme="light"]', L, "light"))
            parts.append("@media (prefers-color-scheme: light) {\n"
                         + block(f"{sel}:not([data-theme])", L, "light", "  ") + "}\n")
    return "\n".join(parts)


def theme_json(pals):
    light = sum(1 for _, t in pals if "light" in t)
    return {
        "name": "Rain",
        "author": "rain-themes",
        "description": f"{len(pals)} palettes from rain-themes in one theme: pick one under Configure. "
                       f"{light} follow degoog's light mode with their official light flavour.",
        "css": "style.css",
        "settingsSchema": [{
            "key": "palette", "label": "Palette", "type": "select",
            "options": [s["slug"] for s, _ in pals],
            "optionLabels": [s["name"] + (" (+ light)" if "light" in t else "") for s, t in pals],
            "description": "The light flavour is used when degoog is in light mode. "
                           "Palettes without one stay dark.",
        }],
        "dataAttrsFromSettings": {"palette": ATTR},
    }


def readme(pals):
    rows = "\n".join(f"| {s['name']} | {t['light']['flavour'] if 'light' in t else 'dark only'} | "
                     f"`{t['background']}` | `{t['accent']}` |" for s, t in pals)
    return f"""# degoog-rain

The [rain-themes]({REPO_URL}) palettes as a theme for
[degoog](https://github.com/degoog-org/degoog), the self-hosted search engine.

This repo is generated by `tools/rain degoog` in rain-themes. Don't edit it by
hand: change the palette spec or the exporter there and export again.

## Install

1. In degoog, open **Settings → Store → Add** and paste
   `{STORE_URL}`.
2. Install **Rain** from the store, then pick it under **Settings → Themes**.
3. Press **Configure** on the Rain card and choose a palette.

Refreshing the repo in the store picks up new palettes and colour fixes.

## Palettes

Palettes with a light flavour switch to it when degoog is in light mode (or
follows a light system theme). The others stay dark.

| Palette | Light mode | Background | Accent |
|---|---|---|---|
{rows}
"""


def outputs(pals):
    """{relative path: bytes} for everything the export owns."""
    css = stylesheet(pals)
    tj = theme_json(pals)
    version = "1.0.0+" + hashlib.sha256((css + json.dumps(tj, sort_keys=True)).encode()).hexdigest()[:7]
    tj["version"] = version
    pkg = {
        "name": "degoog-rain",
        "description": "Rain palettes (Catppuccin, Tokyo Night, Rosé Pine, Kanagawa, Gruvbox and more) for degoog.",
        "author": "rain-themes",
        "repo-image": "logo.png",
        "themes": [{"path": THEME, "name": "Rain", "description": tj["description"], "version": version}],
    }
    dump = lambda o: (json.dumps(o, indent=2, ensure_ascii=False) + "\n").encode()  # noqa: E731
    return {
        "package.json": dump(pkg),
        "logo.png": ICON.read_bytes(),
        "README.md": readme(pals).encode(),
        f"{THEME}/theme.json": dump(tj),
        f"{THEME}/style.css": css.encode(),
        f"{THEME}/author.json": dump({"name": "rain-themes", "url": REPO_URL}),
    }


def check_contrast(pals):
    """Low-contrast pairs, reported but not changed: the colours are the palettes' own upstream values."""
    bad = []
    for spec, t in pals:
        for flavour, b in [("dark", t)] + ([("light", t["light"])] if "light" in t else []):
            for fg, bgk, need in (("text", "background", 4.5), ("text", "raised", 4.5),
                                  ("link", "background", 3.0), ("on_accent", "accent", 3.0)):
                c = contrast(b[fg], b[bgk])
                if c < need:
                    bad.append(f"{spec['slug']} {flavour}: {fg} on {bgk} {c:.1f} < {need}")
    return bad


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", default=str(ROOT.parent / "degoog-rain"))
    ap.add_argument("--check", action="store_true", help="exit 1 if --out is stale; write nothing")
    a = ap.parse_args()
    pals = palettes()
    if not pals:
        sys.exit("no app-theme exports found; run `tools/rain build` first")
    if not a.check:
        for w in check_contrast(pals):
            print(f"note: {w} (upstream colours, kept)")
    out = Path(a.out)
    files = outputs(pals)
    stale = [p for p, b in files.items() if not (out / p).exists() or (out / p).read_bytes() != b]
    if a.check:
        for p in stale:
            print(f"stale: {out / p}")
        sys.exit(1 if stale else 0)
    for p in stale:
        (out / p).parent.mkdir(parents=True, exist_ok=True)
        (out / p).write_bytes(files[p])
    print(f"degoog: {len(pals)} palettes, {len(stale)} file(s) written to {out}")


if __name__ == "__main__":
    main()
